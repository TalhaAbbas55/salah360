/**
 * Generates the static geography the landing page draws, so no map library ships to the browser:
 *   - src/lib/geo/land-points.ts  evenly spread land points for the hero globe (Fibonacci sphere)
 *   - public/world-dots.svg       a dotted equirectangular world map, used as a CSS mask
 *
 * Run once after changing the density: `node scripts/generate-geo-data.mjs`
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(await readFile(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);

// Globe: a Fibonacci sphere keeps the dots evenly spaced even near the poles.
const SPHERE_SAMPLES = 16000;
const golden = Math.PI * (3 - Math.sqrt(5));
const globe = [];
for (let i = 0; i < SPHERE_SAMPLES; i++) {
  const y = 1 - (i / (SPHERE_SAMPLES - 1)) * 2;
  const radius = Math.sqrt(1 - y * y);
  const theta = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lng = ((((Math.atan2(Math.sin(theta) * radius, Math.cos(theta) * radius) * 180) / Math.PI) + 540) % 360) - 180;
  if (lat < -60) continue; // Antarctica only adds noise at the bottom of the globe.
  if (geoContains(land, [lng, lat])) globe.push(Math.round(lat * 10) / 10, Math.round(lng * 10) / 10);
}

await writeFile(
  new URL('../src/lib/geo/land-points.ts', import.meta.url),
  `// Generated by scripts/generate-geo-data.mjs. Do not edit by hand.\n` +
    `/** Flat [lat, lng, lat, lng, …] list of land points for the hero globe. */\n` +
    `export const LAND_POINTS: readonly number[] = [${globe.join(',')}];\n`,
);

// Flat map: a regular lattice reads as a deliberate dotted map rather than noise.
const STEP = 2.4;
const MIN_LAT = -56;
const MAX_LAT = 76;
const width = 360 / STEP;
const height = (MAX_LAT - MIN_LAT) / STEP;
// Each dot is a zero-length round-capped stroke: about a quarter of the bytes of <circle> elements.
const dots = [];
for (let row = 0; row < height; row++) {
  const lat = MAX_LAT - row * STEP - STEP / 2;
  for (let col = 0; col < width; col++) {
    const lng = -180 + col * STEP + STEP / 2;
    if (geoContains(land, [lng, lat])) dots.push(`M${col + 0.5} ${row + 0.5}h0`);
  }
}
await writeFile(
  new URL('../public/world-dots.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" ><path d="${dots.join('')}" stroke="#000" stroke-width="0.64" stroke-linecap="round"/></svg>\n`,
);

console.log(`globe points: ${globe.length / 2}, map dots: ${dots.length} (${width}x${height})`);
